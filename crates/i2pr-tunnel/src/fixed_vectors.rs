/// 154-byte request plaintext used by the frozen vectors. The
/// plaintext content does not affect the transcript; the same
/// expected bytes apply for any 154-byte input.
pub const FIXED_REQUEST_PLAINTEXT: [u8; SHORT_REQUEST_PLAINTEXT_SIZE] = {
    let mut bytes = [0u8; SHORT_REQUEST_PLAINTEXT_SIZE];
    let mut value: u8 = 0;
    let mut i = 0;
    while i < SHORT_REQUEST_PLAINTEXT_SIZE {
        bytes[i] = value;
        value = value.wrapping_add(7);
        i += 1;
    }
    bytes
};

