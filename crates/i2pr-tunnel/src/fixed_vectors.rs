#[cfg(test)]
mod tests {
    use super::*;

    /// Sanity check: the frozen constants are exactly the lengths
    /// the protocol mandates. A regression that changes the
    /// canonical sizes fails this test before any cryptographic
    /// comparison runs.
    #[test]
    fn frozen_constants_have_canonical_lengths() {
        assert_eq!(FIXED_HOP_PRIVATE.len(), EPHEMERAL_KEY_LEN);
        assert_eq!(FIXED_HOP_PUBLIC.len(), EPHEMERAL_KEY_LEN);
        assert_eq!(FIXED_EPHEMERAL_PRIVATE.len(), EPHEMERAL_KEY_LEN);
        assert_eq!(FIXED_EPHEMERAL_PUBLIC.len(), EPHEMERAL_KEY_LEN);
        assert_eq!(FIXED_REQUEST_PLAINTEXT.len(), SHORT_REQUEST_PLAINTEXT_SIZE);
        assert_eq!(FIXED_SEALED_REQUEST.len(), SHORT_BUILD_RECORD_SIZE);
        assert_eq!(FIXED_SLOT_FIVE_NONCE.len(), AEAD_NONCE_LEN);
        assert_eq!(FIXED_SLOT_THREE_CHACHA20_IV.len(), AEAD_NONCE_LEN);
        assert_eq!(FIXED_REPLY_KEY.len(), AEAD_KEY_LEN);
        assert_eq!(FIXED_LAYER_KEY.len(), AEAD_KEY_LEN);
        assert_eq!(FIXED_IV_KEY.len(), AEAD_KEY_LEN);
        assert_eq!(FIXED_OBEP_GARLIC_TAG.len(), 8);
        assert_eq!(FIXED_OBEP_GARLIC_KEY.len(), 32);
    }

    /// The frozen null-prologue hash must match `SHA256` of the
    /// padded protocol name.
    #[test]
    fn null_prologue_hash_matches_sha256_of_padded_protocol_name() {
        use sha2::{Digest, Sha256};
        let mut padded = [0_u8; 32];
        padded[..NOISE_PROTOCOL_NAME.len()].copy_from_slice(NOISE_PROTOCOL_NAME);
        let mut hasher = Sha256::new();
        hasher.update(padded);
        let output = hasher.finalize();
        let mut expected = [0_u8; 32];
        expected.copy_from_slice(&output);
        assert_eq!(NULL_PROLOGUE_HASH, expected);
    }

    /// Slot nonce for slot `n` must place the slot byte at offset 4.
    #[test]
    fn slot_nonce_placement_matches_constant() {
        assert_eq!(FIXED_SLOT_FIVE_NONCE[4], 5);
        for i in [0usize, 1, 2, 3, 5, 6, 7, 8, 9, 10, 11] {
            assert_eq!(FIXED_SLOT_FIVE_NONCE[i], 0);
        }
    }

    /// ChaCha20 IV for slot `n` must place the slot byte at offset 4.
    #[test]
    fn chacha20_iv_placement_matches_constant() {
        assert_eq!(FIXED_SLOT_THREE_CHACHA20_IV[4], 3);
        for i in [0usize, 1, 2, 3, 5, 6, 7, 8, 9, 10, 11] {
            assert_eq!(FIXED_SLOT_THREE_CHACHA20_IV[i], 0);
        }
    }

    /// Independent reference computation uses only low-level
    /// primitives. The frozen constants must agree with this
    /// oracle; otherwise a defect in either side will fail the
    /// test.
    #[test]
    fn independent_oracle_agrees_with_frozen_constants() {
        use sha2::{Digest, Sha256};

        // Null-prologue `h = SHA256(padded_protocol_name)`.
        let mut padded = [0_u8; 32];
        padded[..NOISE_PROTOCOL_NAME.len()].copy_from_slice(NOISE_PROTOCOL_NAME);
        let mut hasher = Sha256::new();
        hasher.update(padded);
        let output = hasher.finalize();
        let mut computed = [0_u8; 32];
        computed.copy_from_slice(&output);
        assert_eq!(computed, NULL_PROLOGUE_HASH);

        // X25519 hop public key.
        let secret = x25519_dalek::StaticSecret::from(FIXED_HOP_PRIVATE);
        let public = x25519_dalek::PublicKey::from(&secret);
        assert_eq!(public.to_bytes(), FIXED_HOP_PUBLIC);

        // X25519 ephemeral public key.
        let eph_secret = x25519_dalek::StaticSecret::from(FIXED_EPHEMERAL_PRIVATE);
        let eph_public = x25519_dalek::PublicKey::from(&eph_secret);
        assert_eq!(eph_public.to_bytes(), FIXED_EPHEMERAL_PUBLIC);

        // X25519 shared secret (sender ephemeral private, hop
        // public).
        let shared = eph_secret.diffie_hellman(&public);
        assert_eq!(shared.as_bytes(), &FIXED_SHARED_SECRET[..]);

        // Transcript hash chain. Steps 1-3 produce the
        // post-ephemeral-h; the production then performs the
        // post-AEAD MixHash that yields POST_REQUEST_H.
        let mut h = NULL_PROLOGUE_HASH;
        let mut hasher = Sha256::new();
        hasher.update(h);
        hasher.update(FIXED_HOP_PUBLIC);
        let output = hasher.finalize();
        h.copy_from_slice(&output);
        let mut hasher = Sha256::new();
        hasher.update(h);
        hasher.update(FIXED_EPHEMERAL_PUBLIC);
        let output = hasher.finalize();
        h.copy_from_slice(&output);
        // POST_REQUEST_H == MixHash(h || ciphertext || tag). The
        // ciphertext bytes for the canonical request are the
        // ciphertext portion of FIXED_SEALED_REQUEST.
        let ciphertext_with_tag = &FIXED_SEALED_REQUEST[48..];
        let mut hasher = Sha256::new();
        hasher.update(h);
        hasher.update(ciphertext_with_tag);
        let output = hasher.finalize();
        h.copy_from_slice(&output);
        assert_eq!(h, POST_REQUEST_H);
    }

    /// Production `EciesX25519BuildCryptography::seal_short_request_with_ephemeral`
    /// must produce the canonical frozen envelope for the
    /// canonical fixed inputs. A defect in the production
    /// transcript state causes this test to fail closed.
    #[test]
    fn production_seal_short_request_matches_frozen_envelope() {
        use crate::build_crypto::BuildCryptography;
        let cryptography = crate::build_crypto::EciesX25519BuildCryptography::new();
        let sealed = cryptography
            .seal_short_request_with_ephemeral(
                &FIXED_REQUEST_PLAINTEXT,
                &FIXED_HOP_PUBLIC,
                &FIXED_HOP_IDENTITY,
                &FIXED_EPHEMERAL_PRIVATE,
            )
            .expect("seal");
        assert_eq!(
            sealed.record.as_ref(),
            &FIXED_SEALED_REQUEST[..],
            "production must match the frozen envelope layout"
        );
        assert_eq!(sealed.ephemeral_pub, FIXED_EPHEMERAL_PUBLIC);
        assert_eq!(
            sealed.state.transcript_hash(),
            POST_REQUEST_H,
            "production must match the frozen post-request transcript hash"
        );
        assert_eq!(
            sealed.state.chaining_key(),
            FIXED_POST_REQUEST_CK,
            "production must match the frozen post-request chaining key"
        );
    }

    /// Production `EciesX25519BuildCryptography::open_short_request`
    /// must reverse the canonical frozen envelope and reach the
    /// frozen post-request state.
    #[test]
    fn production_open_short_request_matches_frozen_state() {
        use crate::build_crypto::BuildCryptography;
        let cryptography = crate::build_crypto::EciesX25519BuildCryptography::new();
        let opened = cryptography
            .open_short_request(
                &FIXED_SEALED_REQUEST,
                &FIXED_HOP_PRIVATE,
                &FIXED_HOP_IDENTITY,
            )
            .expect("open");
        assert_eq!(opened.plaintext.as_ref(), &FIXED_REQUEST_PLAINTEXT[..]);
        assert_eq!(opened.state.transcript_hash(), POST_REQUEST_H);
        assert_eq!(opened.state.chaining_key(), FIXED_POST_REQUEST_CK);
    }

    /// Production `derive_layer_keys` must match the frozen
    /// `SMTunnel*` outputs for the canonical participant and OBEP
    /// continuations.
    #[test]
    fn production_derive_layer_keys_matches_frozen_outputs() {
        use crate::build_crypto::BuildCryptography;
        let cryptography = crate::build_crypto::EciesX25519BuildCryptography::new();
        let sealed = cryptography
            .seal_short_request_with_ephemeral(
                &FIXED_REQUEST_PLAINTEXT,
                &FIXED_HOP_PUBLIC,
                &FIXED_HOP_IDENTITY,
                &FIXED_EPHEMERAL_PRIVATE,
            )
            .expect("seal");
        let participant =
            crate::build_crypto::derive_layer_keys(&sealed.state, false).expect("participant");
        assert_eq!(participant.reply_key(), &FIXED_REPLY_KEY);
        assert_eq!(participant.layer_key(), &FIXED_LAYER_KEY);
        assert_eq!(participant.iv_key(), &FIXED_IV_KEY);
        let obep = crate::build_crypto::derive_layer_keys(&sealed.state, true).expect("obep");
        assert_eq!(
            obep.garlic_reply_key().expect("garlic key"),
            &FIXED_OBEP_GARLIC_KEY
        );
        assert_eq!(
            obep.garlic_reply_tag().expect("garlic tag"),
            &FIXED_OBEP_GARLIC_TAG
        );
    }

    /// Production `ValidatedRecordSlot::nonce()` must place the
    /// slot byte at offset 4 and produce the canonical
    /// 12-byte nonce.
    #[test]
    fn production_validated_record_slot_nonce_matches_constant() {
        let slot = crate::build_crypto::ValidatedRecordSlot::new(5).expect("slot");
        assert_eq!(slot.nonce(), FIXED_SLOT_FIVE_NONCE);
    }
}
