//! Plan 111 frozen independent conformance vectors.
//!
//! This module owns the fixed cryptographic vectors the Plan 111
//! conformance suite asserts against. The expected values are
//! produced by an **independent reference computation** that uses
//! only the low-level crypto primitives (`x25519-dalek`,
//! `sha2`, `chacha20poly1305`, `hkdf`) — never the production
//! [`crate::build_crypto::BuildCryptography`] trait — and the
//! resulting bytes are frozen as Rust constants. Every conformance
//! test then asserts that the production primitive reaches the
//! same bytes for the same inputs.
//!
//! Provenance: the values were generated by
//! `tests/integration/tunnel/conformance_vectors.rs::print_plan111_fixed_vectors`
//! once during the Plan 111 implementation pass; the script uses
//! the same primitives without ever calling into `i2pr-tunnel`.
//! The frozen constants are committed verbatim below.
//!
//! A defect in either the production code or the independent
//! reference code will now cause the conformance tests to fail
//! closed; the production primitive can no longer silently mask a
//! regression in its own transcript state.
#![forbid(unsafe_code)]

